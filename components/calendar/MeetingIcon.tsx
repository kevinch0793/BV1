/** Phone or video glyph for an event's meeting type (nothing if unset). */
export function MeetingIcon({ type, size = 12 }: { type: MeetingType; size?: number }) {
  if (type === "phone") return <PhoneIcon size={size} />;
  if (type === "video") return <VideoIcon size={size} />;
  return null;
}
